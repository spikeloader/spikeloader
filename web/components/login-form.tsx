"use client";

import { useRouter, useSearchParams } from "next/navigation";
import { useCallback, useEffect, useState, type FormEvent } from "react";
import { Button, Field, cx, inputClass } from "./ui";

export function LoginForm() {
  const router = useRouter();
  const next = useSearchParams().get("next");
  const [token, setToken] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  const login = useCallback(
    async (value: string) => {
      setBusy(true);
      setError(null);
      const res = await fetch("/api/auth/login", {
        method: "POST",
        headers: { "content-type": "application/json" },
        body: JSON.stringify({ token: value }),
      });
      if (res.ok) {
        // internal paths only (prevents open redirect)
        router.replace(next?.startsWith("/") && !next.startsWith("//") ? next : "/");
        router.refresh();
        return;
      }
      setError((await res.json().catch(() => ({}))).error ?? "sign-in failed");
      setBusy(false);
    },
    [next, router],
  );

  // link generated by `spikeloader web url`: the token comes in the fragment (#token=…), which is never sent to the server
  // also when the link is opened on an already loaded login page (only the hash changes)
  useEffect(() => {
    const fromHash = () => {
      const t = new URLSearchParams(location.hash.slice(1)).get("token");
      if (!t) return;
      history.replaceState(null, "", location.pathname + location.search);
      login(t);
    };
    fromHash();
    window.addEventListener("hashchange", fromHash);
    return () => window.removeEventListener("hashchange", fromHash);
  }, [login]);

  const onSubmit = (e: FormEvent) => {
    e.preventDefault();
    if (token.trim()) login(token.trim());
  };

  return (
    <form onSubmit={onSubmit} className="flex flex-col gap-4">
      <Field label="Access token">
        <input
          type="password"
          autoFocus
          autoComplete="current-password"
          value={token}
          onChange={(e) => setToken(e.target.value)}
          className={cx(inputClass, error && "border-danger")}
          placeholder="paste the panel token"
        />
      </Field>
      {error && <p className="-mt-2 text-xs text-danger">{error}</p>}
      <Button type="submit" variant="primary" disabled={busy || !token.trim()}>
        {busy ? "Signing in…" : "Sign in"}
      </Button>
      <p className="text-xs text-muted">
        The token lives in <code className="font-mono">.lab/web-token</code>. Show it with <code className="font-mono">spikeloader web token</code>.
      </p>
    </form>
  );
}
